blocks <- list(
  list(family = "binary", link = "probit", dims = 1L, parameters = 1L, y = rbinom(n, 1, .5), outcome = "b1"),
  list(family = "binary", link = "logit", dims = 2L, parameters = 2L, y = rbinom(n, 1, .5), outcome = "b2"),
  list(family = "ordinal", link = "probit", dims = 3L, parameters = 3:5, y = sample(1:4, n, TRUE), outcome = "o1"))
