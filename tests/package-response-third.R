loss_rows <- function(eta, theta) {
  cuts <- c(-Inf, thresholds(theta[3:5]), Inf)
  -interval(cuts[blocks[[3]]$y] - eta[, 3], cuts[blocks[[3]]$y + 1L] - eta[, 3], "probit")
}
scaled <- function(actual, expected, floor = 1e-3) max(abs(actual - expected) / pmax(abs(expected), floor))
