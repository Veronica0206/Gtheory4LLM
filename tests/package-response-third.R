# Binary blocks are the one-cut interval at zero. The closed logistic and
# Mills-ratio forms agree where they are accurate; in the far tails the
# Mills-ratio form loses the bracket 1 - (r + m)(2r + m), and 60-digit
# references decide for the interval route.
for (link in c("probit", "logit")) {
  x <- seq(-40, 40, by = .5)
  y <- rep(c(0L, 1L), length.out = length(x))
  one <- list(n = length(x), q = 1L,
              blocks = list(list(family = "binary", link = link, dims = 1L, parameters = 1L, y = y, outcome = "b")))
  r <- kernel(matrix(x), 0, one)
  t <- third_of(matrix(x), 0, one, r)$blocks[[1]]$third
  via <- interval(ifelse(y == 1L, -x, -Inf), ifelse(y == 1L, Inf, -x), link, third = TRUE)
  stopifnot(identical(t, via$third))
  closed <- if (link == "logit") {
    plogis(x) * plogis(x, lower.tail = FALSE) * (plogis(x, lower.tail = FALSE) - plogis(x))
  } else {
    s <- 2 * y - 1
    m <- s * x
    mills <- exp(dnorm(m, log = TRUE) - pnorm(m, log.p = TRUE))
    s * mills * (1 - (mills + m) * (2 * mills + m))
  }
  moderate <- abs(x) <= 8 & x != 0
  stopifnot(max(abs(t - closed)[moderate] / abs(closed[moderate])) < if (link == "probit") 1e-9 else 1e-12)
}
